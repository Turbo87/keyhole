use approx::assert_abs_diff_eq;
use keyhole_engine::geodesy::{EarthModel, LngLat};

/// A position relative to a line, as Karney's geographiclib measures it.
struct ReferenceOffset {
    earth_model: EarthModel,
    reference_point: LngLat,
    bearing: f64,
    position: LngLat,
    across: f64,
    along: f64,
}

/// A reference offset from positions as (latitude, longitude) and offsets in
/// km.
const fn reference(
    earth_model: EarthModel,
    (reference_latitude, reference_longitude): (f64, f64),
    bearing: f64,
    (latitude, longitude): (f64, f64),
    across: f64,
    along: f64,
) -> ReferenceOffset {
    ReferenceOffset {
        earth_model,
        reference_point: LngLat {
            longitude: reference_longitude,
            latitude: reference_latitude,
        },
        bearing,
        position: LngLat {
            longitude,
            latitude,
        },
        across,
        along,
    }
}

