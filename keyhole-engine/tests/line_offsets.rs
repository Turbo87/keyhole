#[test]
fn line_offsets_match_geographiclib_within_2_mm() {
    for reference in REFERENCE_OFFSETS {
        let ReferenceOffset {
            earth_model,
            reference_point,
            bearing,
            position,
            ..
        } = reference;
        let offset = earth_model.line_offset(reference_point, bearing, position);
        assert_eq!(offset.across >= 0., reference.across >= 0.);
        assert_abs_diff_eq!(offset.across, reference.across, epsilon = 2e-6);
        assert_abs_diff_eq!(offset.along, reference.along, epsilon = 2e-6);
    }
}
